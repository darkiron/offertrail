export const relationshipCopy = (locale: Locale) => (locale === 'en' ? en : fr);
export const formatRelationshipDate = (
  value: string | null | undefined,
  locale: Locale,
  fallback: string,
) =>
  value
    ? new Intl.DateTimeFormat(locale === 'en' ? 'en-GB' : 'fr-FR', {
        day: '2-digit',
        month: 'short',
        year: 'numeric',
      }).format(new Date(value))
    : fallback;
export const normalizeRelationshipKey = (value: string) =>
  value.toLocaleLowerCase().replaceAll('-', '_');

export const relationshipErrorStatus = (error: unknown) => {
  if (typeof error !== 'object' || error === null || !('response' in error))
    return null;
  const response = (error as { response?: { status?: number } }).response;
  return response?.status ?? null;
};
